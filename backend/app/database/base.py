"""Declarative base, metadata conventions and shared model mixins.

A deterministic naming convention is applied to constraints and indexes so
that Alembic autogenerate produces stable, predictable migration names.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import Enum as PyEnum
from typing import Type

from sqlalchemy import DateTime, MetaData, Uuid, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic naming for constraints and indexes.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """Adds a UUID primary key generated by the database (PostgreSQL)."""

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=text("gen_random_uuid()"),
    )


class TimestampMixin:
    """Adds ``created_at`` / ``updated_at`` audit columns."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


def import_models() -> None:
    """Import all model modules so Alembic can discover their metadata.

    Imported lazily to avoid circular imports at module load time.
    """
    from app import models  # noqa: F401  (side effect: registers metadata)


def enum_values(enum_cls: Type[PyEnum]) -> list[str]:
    """Return the persisted string values for a Python enum.

    SQLAlchemy persists enum member *names* by default; the EyeDx contract
    uses lowercase *values*. Pass ``values_callable=enum_values`` to every
    ``Enum`` column so the database stores the contract values.
    """
    return [str(member.value) for member in enum_cls]
